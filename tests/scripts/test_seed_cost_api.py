# CostAnomaly shape
# ---------------------------------------------------------------------------


def test_anomaly_payloads_validate_against_pydantic_model() -> None:
    today = date(2026, 5, 11)
    for payload in seed.build_anomaly_payloads(today):
        model = CostAnomaly.model_validate(payload)
        # Status-ish fields: must be one of the recognized detector names
        # the dashboard knows how to render.
        assert model.detector in {"ce-cost-spike", "ce-rate-of-change"}
        assert model.observed_cost_cents > model.expected_cost_cents
        assert model.deviation_pct > 0
        assert model.suppressed is False


def test_anomaly_signatures_are_stable_across_calls() -> None:
    """Re-running the script must overwrite the same alert-state rows,
    not fan-out duplicates. Signatures are the dedup key, so they must
    be deterministic for the same `today`."""
    today = date(2026, 5, 11)
    a = [p["signature"] for p in seed.build_anomaly_payloads(today)]
    b = [p["signature"] for p in seed.build_anomaly_payloads(today)]
    assert a == b


# ---------------------------------------------------------------------------
# Cache key parity with cost-api models
# ---------------------------------------------------------------------------


def test_cache_key_matches_cost_api_models() -> None:
    """The script's `_cache_key_string` must agree with `CacheKey.to_string()`
    in cost-api, otherwise the seeded rows land at the wrong key and the
    route never sees them."""
    from panakoes_cost_api.models import CacheKey

    from_date = date(2026, 4, 11)
    to_date = date(2026, 5, 11)
    expected = CacheKey(
        query_kind="by-service", from_date=from_date, to_date=to_date
    ).to_string()
    actual = seed._cache_key_string("by-service", from_date, to_date)
    assert actual == expected


