def test_logger_emits_json() -> None:
    log = seed._build_logger()
    # Build a record and run it through the formatter directly.
    fmt = log.handlers[0].formatter
    assert fmt is not None
    import logging as _logging
    record = _logging.LogRecord(
        name="seed_cost_api", level=_logging.INFO,
        pathname=__file__, lineno=1, msg="hello",
        args=(), exc_info=None,
    )
    record.foo = "bar"
    rendered = fmt.format(record)
    import json as _json
    parsed = _json.loads(rendered)
    assert parsed["msg"] == "hello"
    assert parsed["foo"] == "bar"
    assert parsed["level"] == "info"


